function findTopic(name) {
  if (!name) return null
  const n = String(name).trim()
  return TOPICS.find((t) => t.key === n || t.key.includes(n) || (t.aliases || []).some((a) => a === n || a.includes(n))) || null
}

export class Details extends plugin {
  constructor() {
    super({
      name: '[PHP]功能详解',
      dsc: '和平精英插件功能详解',
      event: 'message',
      priority: 1,
      rule: [
        { reg: '^#?和平(插件)?(详解|说明书)$', fnc: 'index' },
        { reg: '^#?和平(插件)?详解\\s*(.+)$', fnc: 'showDetail' },
      ],
    })
  }

  async index(e) {
    const lines = ['和平插件 · 功能详解', '']
    lines.push('发「#和平详解 <主题>」查看详细说明：')
    lines.push('')
    for (const t of TOPICS) lines.push(`· ${t.key}`)
    lines.push('', '也可以直接问：「#和平详解 资产」「#和平详解 签到」')
    await e.reply(lines.join('\n'))
  }

  async showDetail(e) {
    const raw = String(e.msg || '')
    const m = raw.match(/和平(?:插件)?详解\s*(.+)$/)
    const name = m ? m[1].trim() : ''
    const topic = findTopic(name)
    if (!topic) {
      const lines = [`没有「${name}」这个主题`, '', '可用主题：']
      for (const t of TOPICS) lines.push(`· ${t.key}`)
      return e.reply(lines.join('\n'))
    }
    await e.reply(topic.body)
  }
}
